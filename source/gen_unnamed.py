"""Generate initdb/03_unnamed.sql from cur_unnamed.py.

Adds person.name_status (Named / Descriptive), marks the unnamed people already in the Theographic data,
inserts the curated unnamed individuals and their narrative relationships, and recreates the v_atlas_* views
so they carry the new column. Runs after 01_schema.sql and 02_data.sql; safe to re-run on a loaded database.

Usage: python3 gen_unnamed.py [output.sql]   (default ../initdb/03_unnamed.sql)
"""
import os, re, sys
import cur_unnamed as CU

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', 'initdb', '03_unnamed.sql')
SYM = {'Married', 'SiblingOf', 'HalfSiblingOf'}
REL_ID_BASE = 100000   # keeps curated-unnamed edges clear of the 1..n ids from build.py

def verses(passage):
    m = re.fullmatch(r'(.+) (\d+):(\d+)(?:-(\d+))?', passage)
    if not m: raise ValueError(passage)
    return int(m[4]) - int(m[3]) + 1 if m[4] else 1

def q(v):
    if v is None: return 'NULL'
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, int): return str(v)
    return "'" + str(v).replace("'", "''") + "'"

ids = [p['id'] for p in CU.P]
names = [p['name'] for p in CU.P]
assert len(set(ids)) == len(ids), 'duplicate id'
assert len(set(names)) == len(names), 'duplicate name'

out = ['-- Curated unnamed individuals (generated by source/gen_unnamed.py from source/cur_unnamed.py)',
       'SET search_path TO bible;', 'BEGIN;', '',
       "ALTER TABLE person ADD COLUMN IF NOT EXISTS name_status varchar(12) NOT NULL DEFAULT 'Named'",
       "  CHECK (name_status IN ('Named','Descriptive'));", '']

out.append("UPDATE person SET name_status = 'Descriptive' WHERE person_id IN (" +
           ', '.join(q(i) for i in CU.EXISTING_DESCRIPTIVE) + ');')
for pid, name in CU.RENAMES.items():
    out.append(f'UPDATE person SET display_name = {q(name)} WHERE person_id = {q(pid)};')
out.append('')

cols = ['person_id', 'first_name', 'display_name', 'gender', 'testament', 'summary_of_life', 'summary_source',
        'first_reference', 'verse_count', 'name_status']
out.append(f"INSERT INTO person ({', '.join(cols)}) VALUES")
rows = []
for p in CU.P:
    vc = sum(verses(x) for x in p['passages'])
    rows.append('(' + ', '.join(q(v) for v in [p['id'], p['name'], p['name'], p['gender'], p['testament'],
                                                 p['summary'], 'Curated', p['ref'], vc, 'Descriptive']) + ')')
out.append(',\n'.join(rows) + '\nON CONFLICT (person_id) DO NOTHING;\n')

# curated edges are replaced wholesale so edits and removals in cur_unnamed.py take effect on re-run
out.append(f'DELETE FROM relationship WHERE relationship_id > {REL_ID_BASE};')
out.append('INSERT INTO relationship (relationship_id, from_person_id, relationship_type, to_person_id, scripture_reference, source) VALUES')
rows = []
for n, (a, t, b, ref) in enumerate(CU.RELS, 1):
    if t in SYM and a > b: a, b = b, a
    rows.append('(' + ', '.join(q(v) for v in [REL_ID_BASE + n, a, t, b, ref, 'Curated']) + ')')
out.append(',\n'.join(rows) + '\nON CONFLICT DO NOTHING;\n')

# p.* in these views was expanded when they were created, so they must be rebuilt to include name_status
out.append('''DROP VIEW IF EXISTS v_atlas_person, v_atlas_king, v_atlas_prophet, v_atlas_priest, v_atlas_judge, v_atlas_apostle;
CREATE VIEW v_atlas_person AS
SELECT p.* FROM person p WHERE p.primary_role = 'Person';
CREATE VIEW v_atlas_king AS
SELECT p.*, k.royal_title, k.kingdom, k.dynasty, k.reign_start_year, k.reign_end_year,
       k.reign_start_label, k.reign_end_label, k.reign_length_years, k.assessment
FROM person p JOIN king k USING (person_id) WHERE p.primary_role = 'King';
CREATE VIEW v_atlas_prophet AS
SELECT p.*, x.prophet_class, x.books_authored, x.ministry_start_year, x.ministry_end_year, x.audience, x.is_true_prophet
FROM person p JOIN prophet x USING (person_id) WHERE p.primary_role = 'Prophet';
CREATE VIEW v_atlas_priest AS
SELECT p.*, x.priestly_order, x.is_high_priest, x.served_at, x.tenure_start_year, x.tenure_end_year
FROM person p JOIN priest x USING (person_id) WHERE p.primary_role = 'Priest';
CREATE VIEW v_atlas_judge AS
SELECT p.*, x.judge_order, x.tribe_of_origin, x.years_judged, x.oppressor, x.start_year AS judgeship_start_year
FROM person p JOIN judge x USING (person_id) WHERE p.primary_role = 'Judge';
CREATE VIEW v_atlas_apostle AS
SELECT p.*, x.apostle_group, x.prior_occupation, x.calling_reference, x.death_tradition
FROM person p JOIN apostle x USING (person_id) WHERE p.primary_role = 'Apostle';
GRANT SELECT ON ALL TABLES IN SCHEMA bible TO timebase_reader;

COMMIT;''')

open(OUT, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(f'{OUT}: {len(CU.P)} people, {len(CU.RELS)} relationships, '
      f'{len(CU.EXISTING_DESCRIPTIVE)} existing marked Descriptive, {len(CU.RENAMES)} renames')
