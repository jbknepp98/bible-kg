"""Generate migrations/04_phase2_adjustments.sql: project decisions layered on top of 03_text_places.sql.

  1. Place display names follow the project naming rules (cur_place_names.py): no parentheses, no references.
  2. verse_being: Verse -> SpiritualBeing mentions. Theographic verses of the beings excluded from Person
     (Lucifer's verse goes to Satan, whose alias it is), plus the curated passages of curated beings.
  3. verse_divine: Verse -> God (god_1324) and Verse -> Holy Spirit (holy_spirit_7400) from Theographic.
  4. verse_person rows for the curated unnamed people, from their passages.
  6. book summaries, composition dates and author text (cur_books.py).
  5. verse_manifestation: verses recording each divine manifestation, from its curated passages.
  God and the Holy Spirit stay out of person and spiritual_being; they are modelled in 05_divine.sql.
Runs after migrations/03_text_places.sql and initdb/05_divine.sql; idempotent.

Usage: python3 gen_phase2_adjust.py <theographic/json dir> [out.sql]   (default ../migrations/04_phase2_adjustments.sql)
"""
import collections, json, os, re, sys
import cur_books as CB
import cur_divine as CD
import cur_place_names as CPN
import cur_spirits as CS
import cur_unnamed as CU

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = sys.argv[1]
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, '..', 'migrations', '04_phase2_adjustments.sql')
MIGRATION = os.path.join(HERE, '..', 'migrations', '03_text_places.sql')
ALIAS = {'lucifer_1832': 'satan_2476'}                  # Theographic record -> being it is folded into
DIVINE_SRC = ['god_1324', 'holy_spirit_7400']

books = json.load(open(f'{SRC}/books.json'))
osis_of = {b['fields']['bookName']: b['fields']['osisName'] for b in books}
book_ids = [b['fields']['osisName'] for b in books]
verse_osis = {v['id']: v['fields']['osisRef'] for v in json.load(open(f'{SRC}/verses.json'))}
people_src = {p['fields']['personLookup']: p['fields'] for p in json.load(open(f'{SRC}/people.json'))}

def osis_verses(passage):
    m = re.fullmatch(r'(.+) (\d+):(\d+)(?:-(\d+))?', passage)
    lo, hi = int(m[3]), int(m[4] or m[3])
    return [f'{osis_of[m[1]]}.{m[2]}.{v}' for v in range(lo, hi + 1)]

def src_verses(rec):
    return [verse_osis[x] for x in people_src[rec].get('verses', []) if x in verse_osis]

def q(v):
    return 'NULL' if v is None else "'" + str(v).replace("'", "''") + "'"

# ---- 1. place names: check coverage and uniqueness against the migration's own place rows
place_rows = {}
txt = open(MIGRATION, encoding='utf-8').read()
m = re.search(r'^COPY place \((.*?)\) FROM stdin;\n(.*?)^\\\.$', txt, re.S | re.M) or \
    re.search(r'^COPY bible\.place \((.*?)\) FROM stdin;\n(.*?)^\\\.$', txt, re.S | re.M)
if m:
    cols = m[1].split(', ')
    for line in m[2].splitlines():
        r = dict(zip(cols, line.split('\t'))); place_rows[r['place_id']] = r['display_name']
else:   # INSERT form
    for pid, disp in re.findall(r"INSERT INTO place VALUES \('([^']+)', '(?:[^']|'')*', '((?:[^']|'')*)'", txt):
        place_rows[pid] = disp.replace("''", "'")
assert place_rows, 'could not read place rows from 03_text_places.sql'
bad = {k for k, v in place_rows.items() if re.search(r'[()]|\d+:\d+', v)}
unknown = set(CPN.PLACE_NAMES) - set(place_rows)
missing = bad - set(CPN.PLACE_NAMES)
assert not unknown, f'unknown place ids: {sorted(unknown)}'
assert not missing, f'places still needing a name: {sorted(missing)}'
final = {k: CPN.PLACE_NAMES.get(k, v) for k, v in place_rows.items()}
dups = [n for n, c in collections.Counter(final.values()).items() if c > 1]
assert not dups, f'duplicate place names: {dups}'

# ---- 2. verse_being
being = collections.defaultdict(set)
for b in CS.B:
    if b.get('src'):
        being[b['id']].update(src_verses(b['src']))
    else:
        for p in b['passages']: being[b['id']].update(osis_verses(p))
for rec, target in ALIAS.items(): being[target].update(src_verses(rec))
vc = {b['id']: (b.get('vc') or sum(len(osis_verses(p)) for p in b['passages'])) for b in CS.B}
off = {k: (len(v), vc[k]) for k, v in being.items() if len(v) != vc[k]}
assert not off, f'spiritual_being verse_count disagrees with linked verses: {off}'

# ---- 3. verse_divine
divine = {d: set(src_verses(d)) for d in DIVINE_SRC}

# ---- 3b. verses that record each divine manifestation (from its curated passages)
manif = {}
for mf in CD.MANIFESTATIONS:
    vs = set(v for x in mf['passages'] for v in osis_verses(x))
    want = sum(len(osis_verses(x)) for x in mf['passages'])
    assert len(vs) == want, f"{mf['id']}: passages overlap ({len(vs)} distinct of {want})"
    manif[mf['id']] = vs

# ---- 4. curated unnamed people
unnamed = {}
for p in CU.P:
    vs = set(v for x in p['passages'] for v in osis_verses(x))
    want = sum(len(osis_verses(x)) for x in p['passages'])
    assert len(vs) == want, f"{p['id']}: passages overlap ({len(vs)} distinct of {want})"
    unnamed[p['id']] = vs

out = ['-- Phase 2 adjustments (generated by source/gen_phase2_adjust.py). Runs after 03_text_places.sql.',
       'SET search_path TO bible;', 'BEGIN;', '']
out.append('-- 1. place display names (two passes so the UNIQUE constraint never sees a transient clash)')
out.append("UPDATE place SET display_name = '~tmp~' || place_id WHERE place_id IN (" + ', '.join(q(k) for k in CPN.PLACE_NAMES) + ');')
for k, v in sorted(CPN.PLACE_NAMES.items()):
    out.append(f'UPDATE place SET display_name = {q(v)} WHERE place_id = {q(k)};')

out.append('''
-- 2-3. mention tables for spiritual beings and God / the Holy Spirit
DROP VIEW IF EXISTS v_atlas_verse_being, v_atlas_verse_divine;
DROP TABLE IF EXISTS verse_being, verse_divine;
CREATE TABLE verse_being (verse_id varchar(16) NOT NULL REFERENCES verse, being_id varchar(64) NOT NULL REFERENCES spiritual_being,
  source varchar(20) NOT NULL, PRIMARY KEY (verse_id, being_id));
CREATE TABLE verse_divine (verse_id varchar(16) NOT NULL REFERENCES verse, divine_id varchar(64) NOT NULL REFERENCES divine,
  source varchar(20) NOT NULL, PRIMARY KEY (verse_id, divine_id));''')
src_of = {b['id']: ('Theographic' if b.get('src') else 'Curated') for b in CS.B}
rows = [f"({q(v)}, {q(k)}, {q(src_of[k])})" for k in sorted(being) for v in sorted(being[k])]
out.append('INSERT INTO verse_being (verse_id, being_id, source) VALUES\n' + ',\n'.join(rows) + ';')
rows = [f"({q(v)}, {q(k)}, 'Theographic')" for k in sorted(divine) for v in sorted(divine[k])]
out.append('INSERT INTO verse_divine (verse_id, divine_id, source) VALUES\n' + ',\n'.join(rows) + ';')

out.append('''
-- 3b. verse_manifestation: verses that record a manifestation of God (Verse -records-> Manifestation)
DROP VIEW IF EXISTS v_atlas_verse_manifestation;
DROP TABLE IF EXISTS verse_manifestation;
CREATE TABLE verse_manifestation (verse_id varchar(16) NOT NULL REFERENCES verse,
  manifestation_id varchar(64) NOT NULL REFERENCES manifestation, PRIMARY KEY (verse_id, manifestation_id));''')
rows = [f"({q(v)}, {q(k)})" for k in sorted(manif) for v in sorted(manif[k])]
out.append('INSERT INTO verse_manifestation (verse_id, manifestation_id) VALUES\n' + ',\n'.join(rows) + ';')

out.append('''
-- 1c. curated book summaries and composition dates (cur_books.py); widen the label columns first
DROP VIEW IF EXISTS v_atlas_book;
ALTER TABLE book ALTER COLUMN composition_date_label TYPE varchar(160), ALTER COLUMN dating_basis TYPE varchar(120);
CREATE VIEW v_atlas_book AS SELECT book_id, name, short_name, book_order, testament, division, genre, original_language,
  chapter_count, verse_count, author_traditional, authorship_confidence, composition_year_start, composition_year_end,
  composition_date_label, dating_basis, summary, source FROM book;''')
assert set(CB.BOOKS) == set(book_ids), f'book ids differ: {set(CB.BOOKS) ^ set(book_ids)}'
for b, (y0, y1, label, summ) in CB.BOOKS.items():
    assert y0 <= y1, b
    out.append(f"UPDATE book SET composition_year_start = {y0}, composition_year_end = {y1}, composition_date_label = {q(label)}, "
               f"dating_basis = {q(CB.BASIS)}, summary = {q(summ)} WHERE book_id = {q(b)};")
for b, a in CB.AUTHOR_TEXT.items():
    out.append(f'UPDATE book SET author_traditional = {q(a)} WHERE book_id = {q(b)};')

out.append('\n-- 1d. modern names and countries (source/place_modern.tsv from match_place_modern.py)')
for line in open(os.path.join(HERE, 'place_modern.tsv'), encoding='utf-8').read().splitlines()[1:]:
    pid, mname, mcountry, _ = line.split('\t')
    assert pid in place_rows, f'unknown place in place_modern.tsv: {pid}'
    out.append(f"UPDATE place SET modern_name = {q(mname or None)}, modern_country = {q(mcountry or None)} WHERE place_id = {q(pid)};")
out.append('\n-- 1b. a book whose authorship is Unknown asserts no writer (Theographic lists Paul for Hebrews)')
out.append("DELETE FROM book_writer bw USING book b WHERE b.book_id = bw.book_id AND b.authorship_confidence = 'Unknown';")

out.append('\n-- 4. verse links for curated unnamed people (their verse_count is the size of their passages)')
out.append(f"DELETE FROM verse_person WHERE person_id IN ({', '.join(q(k) for k in unnamed)});")
rows = [f"({q(v)}, {q(k)})" for k in sorted(unnamed) for v in sorted(unnamed[k])]
out.append('INSERT INTO verse_person (verse_id, person_id) VALUES\n' + ',\n'.join(rows) + ';')

out.append('''
CREATE VIEW v_atlas_verse_being AS
SELECT x.verse_id, v.book_id, v.chapter_number, v.verse_number, x.being_id, x.source
FROM verse_being x JOIN verse v USING (verse_id);
CREATE VIEW v_atlas_verse_manifestation AS
SELECT x.verse_id, v.book_id, v.chapter_number, v.verse_number, x.manifestation_id
FROM verse_manifestation x JOIN verse v USING (verse_id);
CREATE VIEW v_atlas_verse_divine AS
SELECT x.verse_id, v.book_id, v.chapter_number, v.verse_number, x.divine_id, x.source
FROM verse_divine x JOIN verse v USING (verse_id);
GRANT SELECT ON ALL TABLES IN SCHEMA bible TO timebase_reader;

COMMIT;''')
open(OUT, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(f'{OUT}: {len(CPN.PLACE_NAMES)} place names; verse_being {sum(map(len, being.values()))} '
      f'({len(being)} beings); verse_manifestation {sum(map(len, manif.values()))}; verse_divine {sum(map(len, divine.values()))}; unnamed verse_person {sum(map(len, unnamed.values()))}')
