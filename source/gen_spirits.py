"""Generate initdb/04_spirits.sql from cur_spirits.py.

Creates bible.spiritual_being and bible.spiritual_relationship (edges where at least one end is a spiritual
being; the other end may be a person), the subtype extension tables (angel, demon, principality, false_god),
adds the new relationship types, loads the curated data and creates the Atlas views. Runs after 03_unnamed.sql;
safe to re-run (the tables are owned by this script and rebuilt in full).

Usage: python3 gen_spirits.py [output.sql]   (default ../initdb/04_spirits.sql)
"""
import os, re, sys
import cur_spirits as CS

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', 'initdb', '04_spirits.sql')
OT_BOOKS = {'Genesis', 'Exodus', 'Leviticus', 'Numbers', 'Deuteronomy', 'Joshua', 'Judges', 'Ruth', '1 Samuel',
            '2 Samuel', '1 Kings', '2 Kings', '1 Chronicles', '2 Chronicles', 'Ezra', 'Nehemiah', 'Esther', 'Job',
            'Psalms', 'Proverbs', 'Ecclesiastes', 'Song of Solomon', 'Isaiah', 'Jeremiah', 'Lamentations', 'Ezekiel',
            'Daniel', 'Hosea', 'Joel', 'Amos', 'Obadiah', 'Jonah', 'Micah', 'Nahum', 'Habakkuk', 'Zephaniah',
            'Haggai', 'Zechariah', 'Malachi'}
SYM = {'Married', 'SiblingOf', 'HalfSiblingOf'}

def split_ref(r):
    m = re.fullmatch(r'(.+) (\d+):(\d+)(?:-(\d+))?', r)
    if not m: raise ValueError(r)
    return m[1], int(m[3]), int(m[4]) if m[4] else int(m[3])

def testament(ref):
    return 'Old Testament' if split_ref(ref)[0] in OT_BOOKS else 'New Testament'

def q(v):
    if v is None: return 'NULL'
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, int): return str(v)
    return "'" + str(v).replace("'", "''") + "'"

ids = {b['id'] for b in CS.B}
assert len(ids) == len(CS.B), 'duplicate id'
assert len({b['name'] for b in CS.B}) == len(CS.B), 'duplicate name'

out = ['-- Spiritual beings (generated by source/gen_spirits.py from source/cur_spirits.py)',
       'SET search_path TO bible;', 'BEGIN;', '',
       # the tables are owned by this script and rebuilt on every run, so schema changes here always apply
       '''DROP TABLE IF EXISTS angel, demon, principality, false_god, spiritual_relationship, spiritual_being CASCADE;
CREATE TABLE spiritual_being (
  being_id                   varchar(64)  PRIMARY KEY,
  display_name               varchar(160) NOT NULL UNIQUE,
  also_known_as              text,
  being_kind                 varchar(20)  NOT NULL
                             CHECK (being_kind IN ('Archangel','Angel','Seraph','Adversary','Demon','Spirit','Principality','FalseGod')),
  being_type                 varchar(20)  NOT NULL DEFAULT 'SpiritualBeing'
                             CHECK (being_type IN ('SpiritualBeing','Angel','Demon','Principality','FalseGod')),
  name_status                varchar(12)  NOT NULL CHECK (name_status IN ('Named','Descriptive')),
  testament                  varchar(20)  NOT NULL CHECK (testament IN ('Old Testament','New Testament')),
  appears_in_both_testaments boolean      NOT NULL DEFAULT false,
  summary                    text         NOT NULL,
  summary_source             varchar(40)  NOT NULL,
  first_reference            varchar(40)  NOT NULL,
  verse_count                integer      NOT NULL,
  source_record_id           varchar(32)
);
CREATE TABLE spiritual_relationship (
  relationship_id     integer PRIMARY KEY,
  from_id             varchar(64) NOT NULL,
  from_kind           varchar(16) NOT NULL CHECK (from_kind IN ('Person','SpiritualBeing')),
  relationship_type   varchar(30) NOT NULL REFERENCES relationship_type(relationship_type),
  to_id               varchar(64) NOT NULL,
  to_kind             varchar(16) NOT NULL CHECK (to_kind IN ('Person','SpiritualBeing')),
  scripture_reference varchar(80),
  source              varchar(20) NOT NULL,
  CONSTRAINT spiritual_relationship_unique UNIQUE (from_id, relationship_type, to_id),
  CONSTRAINT spiritual_relationship_no_self CHECK (from_id <> to_id),
  CONSTRAINT spiritual_relationship_has_being CHECK (from_kind = 'SpiritualBeing' OR to_kind = 'SpiritualBeing')
);
-- subtype extension tables, one row per being of that type (like king/prophet/priest for people)
CREATE TABLE angel (
  being_id    varchar(64) PRIMARY KEY REFERENCES spiritual_being(being_id),
  rank        varchar(20) NOT NULL CHECK (rank IN ('Angel','Archangel','Seraph')),
  mission     varchar(20) NOT NULL,
  appeared_as text
);
CREATE TABLE demon (
  being_id    varchar(64) PRIMARY KEY REFERENCES spiritual_being(being_id),
  affliction  text,
  host_count  varchar(10) NOT NULL CHECK (host_count IN ('One','Many'))
);
CREATE TABLE principality (
  being_id    varchar(64) PRIMARY KEY REFERENCES spiritual_being(being_id),
  realm       varchar(40) NOT NULL
);
CREATE TABLE false_god (
  being_id    varchar(64) PRIMARY KEY REFERENCES spiritual_being(being_id),
  culture     varchar(60) NOT NULL,
  domain      varchar(80),
  cult_center text,
  practices   text
);
''']

out.append('INSERT INTO relationship_type (relationship_type, category, is_symmetric, description) VALUES')
out.append(',\n'.join(f'({q(t)}, {q(c)}, false, {q(d)})' for t, c, d in CS.NEW_TYPES) +
           '\nON CONFLICT (relationship_type) DO UPDATE SET description = EXCLUDED.description;\n')

SUBTYPE = {**{k: 'Angel' for k in CS.ANGEL}, **{k: 'Demon' for k in CS.DEMON},
           **{k: 'Principality' for k in CS.PRINCIPALITY}, **{k: 'FalseGod' for k in CS.FALSE_GOD}}
cols = ['being_id', 'display_name', 'also_known_as', 'being_kind', 'being_type', 'name_status', 'testament',
        'appears_in_both_testaments', 'summary', 'summary_source', 'first_reference', 'verse_count', 'source_record_id']
rows = []
for b in CS.B:
    passages = b.get('passages', [])
    vc = b.get('vc') or sum(hi - lo + 1 for _, lo, hi in map(split_ref, passages))
    both = b.get('both', len({testament(p) for p in passages + [b['ref']]}) > 1)
    rows.append('(' + ', '.join(q(v) for v in [
        b['id'], b['name'], b.get('aka'), b['kind'], SUBTYPE.get(b['id'], 'SpiritualBeing'),
        'Named' if b.get('named') else 'Descriptive',
        testament(b['ref']), both, b['summary'], 'Curated', b['ref'], vc, b.get('src')]) + ')')
out.append(f"INSERT INTO spiritual_being ({', '.join(cols)}) VALUES\n" + ',\n'.join(rows) + ';\n')
def ext(table, cols, data):
    vals = [(k,) + (v if isinstance(v, tuple) else (v,)) for k, v in data.items()]
    out.append(f"INSERT INTO {table} ({', '.join(cols)}) VALUES\n" +
               ',\n'.join('(' + ', '.join(q(x) for x in r) + ')' for r in vals) + ';\n')
ext('angel', ['being_id', 'rank', 'mission', 'appeared_as'], CS.ANGEL)
ext('demon', ['being_id', 'affliction', 'host_count'], CS.DEMON)
ext('principality', ['being_id', 'realm'], CS.PRINCIPALITY)
ext('false_god', ['being_id', 'culture', 'domain', 'cult_center', 'practices'], CS.FALSE_GOD)

rows = []
for n, (a, t, b, ref) in enumerate(CS.RELS, 1):
    if t in SYM and a > b: a, b = b, a
    ka = 'SpiritualBeing' if a in ids else 'Person'
    kb = 'SpiritualBeing' if b in ids else 'Person'
    rows.append('(' + ', '.join(q(v) for v in [n, a, ka, t, b, kb, ref, 'Curated']) + ')')
out.append('INSERT INTO spiritual_relationship (relationship_id, from_id, from_kind, relationship_type, to_id, to_kind, '
           'scripture_reference, source) VALUES\n' + ',\n'.join(rows) + ';\n')

# every Person end must exist (a typo would otherwise produce a dangling Atlas edge)
out.append('''DO $$
DECLARE bad text;
BEGIN
  SELECT string_agg(x.id, ', ') INTO bad FROM (
    SELECT from_id AS id FROM spiritual_relationship WHERE from_kind = 'Person'
    UNION SELECT to_id FROM spiritual_relationship WHERE to_kind = 'Person') x
  WHERE NOT EXISTS (SELECT 1 FROM person p WHERE p.person_id = x.id);
  IF bad IS NOT NULL THEN RAISE EXCEPTION 'spiritual_relationship references unknown people: %', bad; END IF;
END $$;
''')

out.append('''-- one view per Atlas type; each being appears in exactly one (by being_type)
CREATE VIEW v_atlas_spiritual_being AS
SELECT b.* FROM spiritual_being b WHERE b.being_type = 'SpiritualBeing';
CREATE VIEW v_atlas_angel AS
SELECT b.*, x.rank, x.mission, x.appeared_as FROM spiritual_being b JOIN angel x USING (being_id);
CREATE VIEW v_atlas_demon AS
SELECT b.*, x.affliction, x.host_count FROM spiritual_being b JOIN demon x USING (being_id);
CREATE VIEW v_atlas_principality AS
SELECT b.*, x.realm FROM spiritual_being b JOIN principality x USING (being_id);
CREATE VIEW v_atlas_false_god AS
SELECT b.*, x.culture, x.domain, x.cult_center, x.practices FROM spiritual_being b JOIN false_god x USING (being_id);
CREATE VIEW v_atlas_spiritual_relationship AS
SELECT r.relationship_id,
       CASE r.from_kind WHEN 'Person' THEN 'Bible.Person.' ELSE 'Bible.Spirit.' END || r.from_id AS from_uri,
       r.relationship_type,
       CASE r.to_kind WHEN 'Person' THEN 'Bible.Person.' ELSE 'Bible.Spirit.' END || r.to_id AS to_uri,
       COALESCE(r.scripture_reference, '') AS scripture_reference, r.source
FROM spiritual_relationship r;
GRANT SELECT ON ALL TABLES IN SCHEMA bible TO timebase_reader;

COMMIT;''')

open(OUT, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(f'{OUT}: {len(CS.B)} beings, {len(CS.RELS)} relationships, {len(CS.NEW_TYPES)} new relationship types')
