"""Generate initdb/05_divine.sql from cur_divine.py.

Creates bible.divine (Godhead and DivinePerson rows), bible.manifestation and bible.divine_relationship (edges
from divine nodes or manifestations to divine nodes, people or spiritual beings), adds the new relationship
types and creates the Atlas views. Runs after 04_spirits.sql; safe to re-run (tables rebuilt in full).

Usage: python3 gen_divine.py [output.sql]   (default ../initdb/05_divine.sql)
"""
import os, re, sys
import cur_divine as CD
import cur_spirits as CS

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', 'initdb', '05_divine.sql')
OT_BOOKS = {'Genesis', 'Exodus', 'Leviticus', 'Numbers', 'Deuteronomy', 'Joshua', 'Judges', 'Ruth', '1 Samuel',
            '2 Samuel', '1 Kings', '2 Kings', '1 Chronicles', '2 Chronicles', 'Ezra', 'Nehemiah', 'Esther', 'Job',
            'Psalms', 'Proverbs', 'Ecclesiastes', 'Song of Solomon', 'Isaiah', 'Jeremiah', 'Lamentations', 'Ezekiel',
            'Daniel', 'Hosea', 'Joel', 'Amos', 'Obadiah', 'Jonah', 'Micah', 'Nahum', 'Habakkuk', 'Zephaniah',
            'Haggai', 'Zechariah', 'Malachi'}

def split_ref(r):
    m = re.fullmatch(r'(.+) (\d+):(\d+)(?:-(\d+))?', r)
    if not m: raise ValueError(r)
    return m[1], int(m[3]), int(m[4]) if m[4] else int(m[3])

def testament(ref):
    return 'Old Testament' if split_ref(ref)[0] in OT_BOOKS else 'New Testament'

def q(v):
    if v is None: return 'NULL'
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, int): return str(v)
    return "'" + str(v).replace("'", "''") + "'"

divine = [dict(CD.GODHEAD, type='Godhead')] + [dict(p, type='DivinePerson') for p in CD.PERSONS]
divine_ids = {d['id'] for d in divine}
man_ids = {m['id'] for m in CD.MANIFESTATIONS}
being_ids = {b['id'] for b in CS.B}
assert not (divine_ids & man_ids), 'id used twice'
assert all(m['of'] in divine_ids for m in CD.MANIFESTATIONS), 'manifestation of unknown divine id'

def kind(i):
    return ('Divine' if i in divine_ids else 'Manifestation' if i in man_ids
            else 'SpiritualBeing' if i in being_ids else 'Person')

out = ['-- God, the divine persons and their manifestations (generated by source/gen_divine.py from source/cur_divine.py)',
       'SET search_path TO bible;', 'BEGIN;', '',
       '''DROP TABLE IF EXISTS divine_relationship, manifestation, divine CASCADE;
CREATE TABLE divine (
  divine_id                  varchar(64)  PRIMARY KEY,
  display_name               varchar(160) NOT NULL UNIQUE,
  divine_type                varchar(20)  NOT NULL CHECK (divine_type IN ('Godhead','DivinePerson')),
  also_known_as              text,
  testament                  varchar(20)  NOT NULL,
  appears_in_both_testaments boolean      NOT NULL,
  summary                    text         NOT NULL,
  summary_source             varchar(40)  NOT NULL,
  first_reference            varchar(40)  NOT NULL,
  verse_count                integer      NOT NULL,
  source_record_id           varchar(32)
);
CREATE TABLE manifestation (
  manifestation_id           varchar(64)  PRIMARY KEY,
  display_name               varchar(160) NOT NULL UNIQUE,
  manifestation_of           varchar(64)  NOT NULL REFERENCES divine(divine_id),
  manifestation_kind         varchar(30)  NOT NULL,
  also_known_as              text,
  testament                  varchar(20)  NOT NULL,
  appears_in_both_testaments boolean      NOT NULL,
  summary                    text         NOT NULL,
  summary_source             varchar(40)  NOT NULL,
  first_reference            varchar(40)  NOT NULL,
  passages                   text         NOT NULL,
  verse_count                integer      NOT NULL
);
CREATE TABLE divine_relationship (
  relationship_id     integer PRIMARY KEY,
  from_id             varchar(64) NOT NULL,
  from_kind           varchar(16) NOT NULL CHECK (from_kind IN ('Divine','Manifestation')),
  relationship_type   varchar(30) NOT NULL REFERENCES relationship_type(relationship_type),
  to_id               varchar(64) NOT NULL,
  to_kind             varchar(16) NOT NULL CHECK (to_kind IN ('Divine','Manifestation','Person','SpiritualBeing')),
  scripture_reference varchar(80),
  interpretation      varchar(40),
  source              varchar(20) NOT NULL,
  CONSTRAINT divine_relationship_unique UNIQUE (from_id, relationship_type, to_id)
);
''']

out.append('INSERT INTO relationship_type (relationship_type, category, is_symmetric, description) VALUES')
out.append(',\n'.join(f'({q(t)}, {q(c)}, false, {q(d)})' for t, c, d in CD.NEW_TYPES) +
           '\nON CONFLICT (relationship_type) DO UPDATE SET description = EXCLUDED.description;\n')

rows = [[d['id'], d['name'], d['type'], d.get('aka'), testament(d['ref']), d.get('both', False), d['summary'],
         'Curated', d['ref'], d['vc'], d.get('src')] for d in divine]
out.append('INSERT INTO divine (divine_id, display_name, divine_type, also_known_as, testament, appears_in_both_testaments, '
           'summary, summary_source, first_reference, verse_count, source_record_id) VALUES\n' +
           ',\n'.join('(' + ', '.join(q(v) for v in r) + ')' for r in rows) + ';\n')

rows = []
for m in CD.MANIFESTATIONS:
    vc = sum(hi - lo + 1 for _, lo, hi in map(split_ref, m['passages']))
    both = len({testament(p) for p in m['passages'] + [m['ref']]}) > 1
    rows.append([m['id'], m['name'], m['of'], m['kind'], m.get('aka'), testament(m['ref']), both, m['summary'],
                 'Curated', m['ref'], '; '.join(m['passages']), vc])
out.append('INSERT INTO manifestation (manifestation_id, display_name, manifestation_of, manifestation_kind, also_known_as, '
           'testament, appears_in_both_testaments, summary, summary_source, first_reference, passages, verse_count) VALUES\n' +
           ',\n'.join('(' + ', '.join(q(v) for v in r) + ')' for r in rows) + ';\n')

# ManifestationOf edges come from manifestation.manifestation_of; the rest are curated
rels = [(m['id'], 'ManifestationOf', m['of'], m['ref'], None) for m in CD.MANIFESTATIONS] + CD.RELS
rows = [[n, a, kind(a), t, b, kind(b), ref, interp, 'Curated'] for n, (a, t, b, ref, interp) in enumerate(rels, 1)]
out.append('INSERT INTO divine_relationship (relationship_id, from_id, from_kind, relationship_type, to_id, to_kind, '
           'scripture_reference, interpretation, source) VALUES\n' +
           ',\n'.join('(' + ', '.join(q(v) for v in r) + ')' for r in rows) + ';\n')

out.append('''DO $$
DECLARE bad text;
BEGIN
  SELECT string_agg(r.to_id, ', ') INTO bad FROM divine_relationship r
  WHERE (r.to_kind = 'Person' AND NOT EXISTS (SELECT 1 FROM person p WHERE p.person_id = r.to_id))
     OR (r.to_kind = 'SpiritualBeing' AND NOT EXISTS (SELECT 1 FROM spiritual_being b WHERE b.being_id = r.to_id));
  IF bad IS NOT NULL THEN RAISE EXCEPTION 'divine_relationship references unknown targets: %', bad; END IF;
END $$;

CREATE VIEW v_atlas_godhead AS SELECT d.* FROM divine d WHERE d.divine_type = 'Godhead';
CREATE VIEW v_atlas_divine_person AS SELECT d.* FROM divine d WHERE d.divine_type = 'DivinePerson';
CREATE VIEW v_atlas_manifestation AS SELECT m.* FROM manifestation m;
CREATE VIEW v_atlas_divine_relationship AS
SELECT r.relationship_id,
       'Bible.Divine.' || r.from_id AS from_uri,   -- divine nodes and manifestations share one id space
       r.relationship_type,
       CASE r.to_kind WHEN 'Person' THEN 'Bible.Person.' WHEN 'SpiritualBeing' THEN 'Bible.Spirit.' ELSE 'Bible.Divine.' END
         || r.to_id AS to_uri,
       COALESCE(r.scripture_reference, '') AS scripture_reference, COALESCE(r.interpretation, '') AS interpretation, r.source
FROM divine_relationship r;
GRANT SELECT ON ALL TABLES IN SCHEMA bible TO timebase_reader;

COMMIT;''')

open(OUT, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(f'{OUT}: {len(divine)} divine, {len(CD.MANIFESTATIONS)} manifestations, {len(rels)} relationships')
