"""Generate migrations/05_events.sql: biblical events from Theographic Bible Metadata (CC BY-SA 4.0).

Tables: event, event_verse (the verses that record it), event_participant (people, spiritual beings and God /
the Holy Spirit involved), event_place, event_relation (SubEventOf: an event within a larger one; Follows: the
event's predecessor in the timeline). Views v_atlas_event* for Connect. Joins on Theographic keys only.
Runs after 04_phase2_adjustments.sql (needs person, spiritual_being, divine, place, verse); idempotent.

Usage: python3 etl_events.py <theographic/json dir> [out.sql]   (default ../migrations/05_events.sql)
"""
import json, os, re, sys
import cur_events as CE
import cur_spirits as CS

SRC = sys.argv[1]
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, '..', 'migrations', '05_events.sql')
DIVINE = {'god_1324', 'holy_spirit_7400'}
BEINGS = {b['id'] for b in CS.B} | {'lucifer_1832'}
ALIAS = {'lucifer_1832': 'satan_2476'}

load = lambda f: json.load(open(f'{SRC}/{f}.json'))
events = [dict(e['fields'], _rec=e['id']) for e in load('events')]
person_of = {p['id']: p['fields']['personLookup'] for p in load('people')}
place_of = {p['id']: p['fields']['placeLookup'] for p in load('places')}
books = {b['id']: b['fields']['bookName'] for b in load('books')}
verse_of, label_of, sort_of = {}, {}, {}
for v in load('verses'):
    f = v['fields']; b, c, n = f['osisRef'].split('.')
    verse_of[v['id']] = f['osisRef']; label_of[f['osisRef']] = f"{books[f['book'][0]]} {c}:{n}"; sort_of[f['osisRef']] = f['verseID']
event_id = {e['_rec']: f"event_{e['eventID']}" for e in events}

def q(v):
    if v is None: return 'NULL'
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, (int, float)): return str(v)
    return "'" + str(v).replace("'", "''") + "'"

def year_label(y):
    return f'{-y} BC' if y < 0 else f'AD {y}' if y > 0 else '1 BC'

def parse_start(s):
    # '-1749' (a year) or '0030-05-01' (an exact date; the year is AD unless signed)
    m = re.fullmatch(r'(-?\d+)(?:-(\d\d)-(\d\d))?', s.strip())
    if not m: raise ValueError(f'unrecognised startDate {s!r}')
    return int(m[1]), (s.strip() if m[2] else None)

def end_year(start, duration):
    m = re.fullmatch(r'([\d.]+)Y', duration or '')
    return start + int(float(m[1])) if m else start      # days, weeks and months end in the same year

ev_rows, ev_verse, ev_part, ev_place, ev_rel, names = [], [], [], [], [], set()
for e in events:
    eid = event_id[e['_rec']]
    title = CE.RENAMES.get(f"by_title:{e['title']}", e['title'])
    assert not re.search(r'[()]|\d+:\d+', title), f'title breaks naming rules: {title}'
    assert title not in names, f'duplicate event title: {title}'
    names.add(title)
    y0, exact = parse_start(e['startDate']); y1 = end_year(y0, e.get('duration'))
    vs = sorted({verse_of[x] for x in e.get('verses', [])}, key=lambda r: sort_of[r])
    ev_rows.append([eid, int(e['eventID']), title, y0, y1, year_label(y0), year_label(y1), exact, e.get('duration') or '',
                    float(e['sortKey']) if e.get('sortKey') is not None else float(y0), e.get('notes'),
                    CE.DATING_BASIS, len(vs), label_of[vs[0]] if vs else None])
    ev_verse += [(eid, v) for v in vs]
    for x in dict.fromkeys(e.get('participants', [])):
        pid = person_of[x]
        kind = 'Divine' if pid in DIVINE else 'SpiritualBeing' if pid in BEINGS else 'Person'
        ev_part.append((eid, ALIAS.get(pid, pid), kind))
    ev_place += [(eid, place_of[x]) for x in dict.fromkeys(e.get('locations', []))]
    ev_rel += [(eid, 'SubEventOf', event_id[x]) for x in e.get('partOf', []) if x in event_id]
    ev_rel += [(eid, 'Follows', event_id[x]) for x in e.get('predecessor', []) if x in event_id]
ev_part = list(dict.fromkeys(ev_part))

out = ['-- Phase 3: events (generated by source/etl_events.py from Theographic Bible Metadata, CC BY-SA 4.0)',
       'SET search_path TO bible;', 'BEGIN;',
       'DROP TABLE IF EXISTS event_relation, event_place, event_participant, event_verse, event CASCADE;',
       '''CREATE TABLE event (
  event_id varchar(20) PRIMARY KEY, source_event_id integer NOT NULL UNIQUE, display_name varchar(160) NOT NULL UNIQUE,
  start_year integer NOT NULL, end_year integer NOT NULL, start_label varchar(20) NOT NULL, end_label varchar(20) NOT NULL,
  start_date varchar(12),
  duration varchar(20) NOT NULL, sort_key double precision NOT NULL, notes text, dating_basis varchar(120) NOT NULL,
  verse_count integer NOT NULL, first_reference varchar(40));
CREATE TABLE event_verse (event_id varchar(20) REFERENCES event, verse_id varchar(16) REFERENCES verse, PRIMARY KEY (event_id, verse_id));
CREATE TABLE event_participant (event_id varchar(20) REFERENCES event, participant_id varchar(64) NOT NULL,
  participant_kind varchar(16) NOT NULL CHECK (participant_kind IN ('Person','SpiritualBeing','Divine')),
  PRIMARY KEY (event_id, participant_id));
CREATE TABLE event_place (event_id varchar(20) REFERENCES event, place_id varchar(64) REFERENCES place, PRIMARY KEY (event_id, place_id));
CREATE TABLE event_relation (event_id varchar(20) REFERENCES event, relation_type varchar(12) NOT NULL CHECK (relation_type IN ('SubEventOf','Follows')),
  other_event_id varchar(20) REFERENCES event, PRIMARY KEY (event_id, relation_type, other_event_id));''']
cols = 'event_id, source_event_id, display_name, start_year, end_year, start_label, end_label, start_date, duration, sort_key, notes, dating_basis, verse_count, first_reference'
out.append(f'INSERT INTO event ({cols}) VALUES\n' + ',\n'.join('(' + ', '.join(q(v) for v in r) + ')' for r in ev_rows) + ';')
for table, cols_, rows in [('event_verse', 'event_id, verse_id', ev_verse),
                           ('event_participant', 'event_id, participant_id, participant_kind', ev_part),
                           ('event_place', 'event_id, place_id', ev_place),
                           ('event_relation', 'event_id, relation_type, other_event_id', ev_rel)]:
    out.append(f'INSERT INTO {table} ({cols_}) VALUES\n' + ',\n'.join('(' + ', '.join(q(v) for v in r) + ')' for r in rows) + ';')
out.append('''DO $$
DECLARE bad text;
BEGIN
  SELECT string_agg(participant_id, ', ') INTO bad FROM event_participant x
  WHERE (participant_kind = 'Person' AND NOT EXISTS (SELECT 1 FROM person p WHERE p.person_id = x.participant_id))
     OR (participant_kind = 'SpiritualBeing' AND NOT EXISTS (SELECT 1 FROM spiritual_being b WHERE b.being_id = x.participant_id))
     OR (participant_kind = 'Divine' AND NOT EXISTS (SELECT 1 FROM divine d WHERE d.divine_id = x.participant_id));
  IF bad IS NOT NULL THEN RAISE EXCEPTION 'event participants not found: %', bad; END IF;
END $$;

CREATE VIEW v_atlas_event AS SELECT e.* FROM event e;
CREATE VIEW v_atlas_event_verse AS SELECT x.event_id, x.verse_id, v.book_id FROM event_verse x JOIN verse v USING (verse_id);
CREATE VIEW v_atlas_event_participant AS
SELECT x.event_id, x.participant_id, x.participant_kind,
       CASE x.participant_kind WHEN 'Person' THEN 'Bible.Person.' WHEN 'SpiritualBeing' THEN 'Bible.Spirit.' ELSE 'Bible.Divine.' END
         || x.participant_id AS participant_uri
FROM event_participant x;
CREATE VIEW v_atlas_event_place AS SELECT x.* FROM event_place x;
CREATE VIEW v_atlas_event_relation AS SELECT x.* FROM event_relation x;
GRANT SELECT ON ALL TABLES IN SCHEMA bible TO timebase_reader;
COMMIT;''')
open(OUT, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(f'{OUT}: {len(ev_rows)} events, {len(ev_verse)} verse links, {len(ev_part)} participants, '
      f'{len(ev_place)} places, {len(ev_rel)} event relations')
