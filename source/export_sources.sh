#!/bin/sh
# Dump the authors and works the document-core service added after approval (migrations/07_sources.sql tables) into
# migrations/08_sources_data.sql, so a rebuilt database gets them back. Run after approving new sources, then commit.
set -e
cd "$(dirname "$0")/.."
. ./bible.env
{
  echo "-- Authors and works approved through the document-core service. Generated by source/export_sources.sh; do not edit."
  echo "-- Apply after 07_sources.sql. Rows already present are skipped."
  docker exec bible-pg pg_dump -U "$POSTGRES_USER" -d "$POSTGRES_DB" --data-only --column-inserts --on-conflict-do-nothing \
    --no-owner --no-privileges -t bible.author -t bible.work -t bible.work_part -t bible.work_credit \
    -t bible.document_credit -t bible.document_work -t bible.work_passage | grep -v -E '^(--|SET |SELECT pg_catalog|\\(un)?restrict)' | sed '/^$/d'
} > migrations/08_sources_data.sql
grep -c '^INSERT' migrations/08_sources_data.sql | sed 's/$/ rows exported to migrations\/08_sources_data.sql/'
