"""Generate migrations/90_esv_trial.sql: a trial ESV text, in its own table so it can be removed cleanly.

Reads the SQLite dump as text (it is never executed), maps its book codes to OSIS ids by canonical order, and
applies cur_esv_patches.py: the 16 verses not in the ESV main text get empty text and a note, text lost at
numbering differences is restored, '--' becomes an em dash and stray curly quotes are straightened.
The generated SQL contains the licensed ESV text and is git-ignored; do not commit or publish it.

Remove the trial:  DROP VIEW bible.v_atlas_esv_text; DROP TABLE bible.esv_text;
                   then remove TextEsv / EsvNote from the Connect verse queries and the Atlas verse maps.

Usage: python3 gen_esv_trial.py <esv sqlite.sql> <theographic/json dir> [out.sql]
"""
import json, os, re, sys
import cur_esv_patches as EP

DUMP, THEO = sys.argv[1], sys.argv[2]
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[3] if len(sys.argv) > 3 else os.path.join(HERE, '..', 'migrations', '90_esv_trial.sql')
ROW = re.compile(r"""^INSERT INTO "esv" \("verseid","book","chapter","versenumber","verse"\) VALUES """
                 r"""\((\d+),'((?:[^']|'')*)',(\d+),(\d+),'((?:[^']|'')*)'\);$""")

osis_books = [b['fields']['osisName'] for b in sorted(json.load(open(f'{THEO}/books.json')),
                                                       key=lambda b: int(b['fields']['bookOrder']))]
rows, dump_books, skipped = [], [], 0
for line in open(DUMP, encoding='utf-8'):
    if not line.startswith('INSERT'): continue
    m = ROW.match(line.rstrip('\n'))
    if not m: skipped += 1; continue
    b = m[2].replace("''", "'")
    if b not in dump_books: dump_books.append(b)
    rows.append((b, int(m[3]), int(m[4]), m[5].replace("''", "'")))
assert skipped == 0 and len(dump_books) == 66, (skipped, len(dump_books))
code = dict(zip(dump_books, osis_books))
text = {f'{code[b]}.{c}.{v}': t for b, c, v, t in rows}
assert len(text) == 31102

def tidy(t):
    return t.replace('--', '—').replace('“', '"').replace('”', '"')

JOIN = re.compile(r'(?<=[a-z\)])([.!?;:,])([A-Z(\[])')

def repair(vid, t):
    """Fix the dump's structural defects; returns (text, list of notes)."""
    notes = []
    b, c, v = vid.split('.')
    if b == 'Ps' and c == '119' and int(v) % 8 == 0:
        t2 = re.sub(r'\s*(' + '|'.join(map(re.escape, EP.PS119_LETTERS)) + r')$', '', t)
        if t2 != t: t = t2; notes.append('Psalm 119 stanza heading removed from the end of the verse.')
    if vid in EP.MOVE_TO_NOTE:
        frag = EP.MOVE_TO_NOTE[vid]; assert t.endswith(frag), vid
        t = t[:-len(frag)]; notes.append(frag.strip(' []').rstrip('.') + '.')
    if vid in EP.UNBRACKET:
        assert t.count('[') == 1 and t.endswith(']'), vid
        t = t.replace('[', ' ').rstrip(']'); notes.append(EP.UNBRACKET[vid])
    if JOIN.search(t):
        if vid in EP.QUOTE_JOINS:
            t = JOIN.sub(lambda m: m[1] + '" "' + m[2] if t[:m.start()].count('"') % 2 else m[1] + ' ' + m[2], t)
            notes.append('Quotation marks lost by the import were restored (checked against esv.org).')
        else:
            t = JOIN.sub(lambda m: m[1] + ' ' + m[2], t)
        t = re.sub(r'  +', ' ', t)
    return t, notes

out_rows = []
for vid, t in text.items():
    status, note = 'as imported', EP.NOTES.get(vid)
    if vid in EP.NOT_IN_ESV:
        assert t == 'See Footnote' or vid == 'Matt.17.21', (vid, t)
        footnote = f' Some manuscripts add: "{t}"' if t != 'See Footnote' else ''
        t, status, note = '', 'not in ESV text', EP.NOT_IN_ESV_NOTE + footnote
    elif vid in EP.PATCHES:
        how, extra, note = EP.PATCHES[vid]
        assert how == 'append' and extra.strip() not in t
        t, status = t + extra, 'patched'
    elif t == 'See Footnote':
        raise SystemExit(f'unexpected placeholder at {vid}')
    tidied = tidy(t)
    if tidied != t and status == 'as imported': status = 'typography fixed'
    repaired, fixes = repair(vid, tidied)
    if repaired != tidied:
        if status in ('as imported', 'typography fixed'): status = 'defect fixed'
        note = ' '.join(filter(None, [note] + fixes)) or None
    out_rows.append((vid, repaired, status, note))

q = lambda v: 'NULL' if v is None else "'" + v.replace("'", "''") + "'"
with open(OUT, 'w', encoding='utf-8') as f:
    f.write('-- TRIAL ESV TEXT: licensed; generated by source/gen_esv_trial.py; git-ignored. Do not commit or publish.\n')
    f.write('SET search_path TO bible;\nBEGIN;\nDROP VIEW IF EXISTS v_atlas_esv_text;\nDROP TABLE IF EXISTS esv_text;\n')
    f.write("""CREATE TABLE esv_text (
  verse_id    varchar(16) PRIMARY KEY REFERENCES verse,
  text        text NOT NULL,
  status      varchar(20) NOT NULL CHECK (status IN ('as imported','typography fixed','defect fixed','patched','not in ESV text')),
  note        text,
  edition     varchar(80) NOT NULL,
  attribution text NOT NULL);
COMMENT ON TABLE esv_text IS 'Trial ESV text from an unofficial copy of the 2001 text, patched. Remove with DROP TABLE esv_text.';
""")
    f.write('INSERT INTO esv_text (verse_id, text, status, note, edition, attribution) VALUES\n')
    f.write(',\n'.join(f'({q(v)}, {q(t)}, {q(s)}, {q(n)}, {q(EP.EDITION)}, {q(EP.ATTRIBUTION)})' for v, t, s, n in out_rows))
    f.write(""";
CREATE VIEW v_atlas_esv_text AS SELECT verse_id, text AS text_esv, COALESCE(note, '') AS esv_note FROM esv_text;
GRANT SELECT ON ALL TABLES IN SCHEMA bible TO timebase_reader;
COMMIT;
""")
from collections import Counter
print(f'{OUT}: {len(out_rows)} verses', dict(Counter(s for _, _, s, _ in out_rows)))
